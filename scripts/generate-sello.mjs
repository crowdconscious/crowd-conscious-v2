/**
 * Generates both official Sello badges ("EMPRESA CONSCIENTE" for companies, "ESFUERZO CONSCIENTE" for other org types) as font-free SVG
 * (text converted to outlines so it renders identically everywhere) plus
 * transparent PNGs. Re-run only if the design changes:
 *   npm i --no-save opentype.js@1 && node scripts/generate-sello.mjs
 * Outputs: lib/org/sello-svg.generated.ts, public/sello/*.svg|png
 */
import fs from 'node:fs'
import path from 'node:path'
import opentype from 'opentype.js'
import sharp from 'sharp'

const FONT = process.env.SELLO_FONT || '/usr/share/fonts/truetype/sand-box/google/Poppins/Poppins-Bold.ttf'
const VARIANTS = { empresa: 'EMPRESA CONSCIENTE', esfuerzo: 'ESFUERZO CONSCIENTE' }
const C = 256
const f = (n) => Math.round(n * 100) / 100
const font = opentype.loadSync(FONT)

// Curved top text: glyphs upright, centred on the top of a circle.
const size = 35, tracking = 4.5, rBase = 175, rMid = rBase + size * 0.36
function textPathsFor(TEXT) {
const glyphs = font.stringToGlyphs(TEXT)
const adv = glyphs.map((g) => (g.advanceWidth / font.unitsPerEm) * size)
const total = adv.reduce((a, b) => a + b, 0) + tracking * (glyphs.length - 1)
let s = -total / 2
const textPaths = []
glyphs.forEach((g, i) => {
  const mid = s + adv[i] / 2
  const ang = mid / rMid // radians from top, clockwise
  const p = g.getPath(-adv[i] / 2, 0, size)
  const cos = Math.cos(ang), sin = Math.sin(ang)
  const bx = C + rBase * Math.sin(ang), by = C - rBase * Math.cos(ang)
  const tr = (x, y) => [f(bx + x * cos - y * sin), f(by + x * sin + y * cos)]
  let d = ''
  for (const c of p.commands) {
    if (c.type === 'M' || c.type === 'L') d += c.type + tr(c.x, c.y).join(' ')
    else if (c.type === 'Q') d += 'Q' + [...tr(c.x1, c.y1), ...tr(c.x, c.y)].join(' ')
    else if (c.type === 'C') d += 'C' + [...tr(c.x1, c.y1), ...tr(c.x2, c.y2), ...tr(c.x, c.y)].join(' ')
    else if (c.type === 'Z') d += 'Z'
  }
  if (d) textPaths.push(d)
  s += adv[i] + tracking
})

  return textPaths
}

function star(cx, cy, R, r = R * 0.45) {
  let d = ''
  for (let k = 0; k < 10; k++) {
    const a = (Math.PI / 5) * k - Math.PI / 2, rr = k % 2 ? r : R
    d += (k ? 'L' : 'M') + f(cx + rr * Math.cos(a)) + ' ' + f(cy + rr * Math.sin(a))
  }
  return d + 'Z'
}
const stars = [-60, -40, -20, 0, 20, 40, 60].map((deg) => {
  const a = (deg * Math.PI) / 180
  return star(C + 190 * Math.sin(a), C + 190 * Math.cos(a), 11)
}).join('')

// Centre icon: the Crowd Conscious fingerprint/pin mark (scripts/sello/cc-mark.svg,
// potrace of the official logo PNG). Mark bbox in its own space: x 102..393, y 92..432.
const markSvg = fs.readFileSync(new URL('./sello/cc-mark.svg', import.meta.url), 'utf8')
const markD = markSvg.match(/<path fill="url\(#g\)" d="([^"]+)"/)[1]
const MARK_H = 132, ms = MARK_H / 340
const mark = `<g transform="translate(256 256) scale(${f(ms)}) translate(-247.5 -262) translate(0 500) scale(0.025 -0.025)"><path fill="url(#__ID__-m)" d="${markD}"/></g>`

// `__ID__` is replaced per instance so several badges on one page keep unique gradient ids.
const bodyFor = (textPaths) => `<defs>
<linearGradient id="__ID__-g" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#5BC8C4"/><stop offset="1" stop-color="#74E59A"/></linearGradient>
<linearGradient id="__ID__-gu" gradientUnits="userSpaceOnUse" x1="60" y1="60" x2="452" y2="452"><stop offset="0" stop-color="#5BC8C4"/><stop offset="1" stop-color="#74E59A"/></linearGradient>
<linearGradient id="__ID__-m" x1="0" y1="1" x2="1" y2="0"><stop offset="0" stop-color="#4FC0C2"/><stop offset="1" stop-color="#7DDA55"/></linearGradient>
<radialGradient id="__ID__-c" cx="0.5" cy="0.5" r="0.5"><stop offset="0" stop-color="#1B2436"/><stop offset="1" stop-color="#121826"/></radialGradient>
</defs>
<circle cx="256" cy="256" r="252" fill="url(#__ID__-g)"/>
<circle cx="256" cy="256" r="238" fill="#141A28"/>
<circle cx="256" cy="256" r="224" fill="none" stroke="url(#__ID__-gu)" stroke-width="2.5"/>
<path fill="url(#__ID__-gu)" d="${textPaths.join('')}"/>
<circle cx="${C - 190}" cy="256" r="6" fill="url(#__ID__-gu)"/><circle cx="${C + 190}" cy="256" r="6" fill="url(#__ID__-gu)"/>
<circle cx="256" cy="256" r="146" fill="none" stroke="url(#__ID__-gu)" stroke-width="2.5"/>
<circle cx="256" cy="256" r="134" fill="url(#__ID__-c)" stroke="url(#__ID__-gu)" stroke-width="7"/>
<path fill="url(#__ID__-gu)" d="${stars}"/>
${mark}`

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..')
const bodies = Object.fromEntries(Object.entries(VARIANTS).map(([k, t]) => [k, bodyFor(textPathsFor(t))]))
fs.writeFileSync(path.join(root, 'lib/org/sello-svg.generated.ts'),
  `// GENERATED by scripts/generate-sello.mjs. Do not edit by hand.\nexport const SELLO_TEXTS = ${JSON.stringify(VARIANTS)} as const\nexport const SELLO_SVG_BODIES: Record<keyof typeof SELLO_TEXTS, string> = ${JSON.stringify(bodies)}\n`)
const out = path.join(root, 'public/sello')
fs.mkdirSync(out, { recursive: true })
for (const [k, t] of Object.entries(VARIANTS)) {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" width="512" height="512" role="img" aria-label="Sello ${t}">${bodies[k].replaceAll('__ID__', 'sello')}</svg>`
  const base = `sello-${k}-consciente`
  fs.writeFileSync(path.join(out, `${base}.svg`), svg)
  for (const px of [1024, 512]) await sharp(Buffer.from(svg), { density: (72 * px) / 512 }).resize(px, px).png().toFile(path.join(out, `${base}-${px}.png`))
}
console.log('ok', Object.keys(VARIANTS))
